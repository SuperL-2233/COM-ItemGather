import { test, expect, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/login')
  await page.getByLabel('用户名').fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('e2e-admin-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/ideas$/)
}

test('道具与配方默认使用列表，保留卡片内容并记忆浏览偏好', async ({ page }) => {
  await login(page)
  const { csrf_token } = await (await page.request.get('/api/auth/me')).json()
  const toolResponse = await page.request.post('/api/tools', {
    headers: { 'X-CSRF-Token': csrf_token },
    data: { chinese_name: '布局验收道具', english_name: 'Layout Tool', use_category: '主动', development_status: 'design', tool_settings: { effect: '布局验收效果', sources: [{ method: '购买' }] } },
  })
  expect(toolResponse.ok(), await toolResponse.text()).toBeTruthy()
  const tool = await toolResponse.json()
  const outputResponse = await page.request.post('/api/products', { headers: { 'X-CSRF-Token': csrf_token }, data: { chinese_name: '布局验收产物', development_status: 'production' } })
  expect(outputResponse.ok(), await outputResponse.text()).toBeTruthy()
  const output = await outputResponse.json()
  const groupResponse = await page.request.post('/api/recipe-groups', { headers: { 'X-CSRF-Token': csrf_token }, data: { output_id: output.id } })
  expect(groupResponse.ok(), await groupResponse.text()).toBeTruthy()
  const group = await groupResponse.json()

  await page.goto('/tools')
  const toolSwitch = page.getByRole('group', { name: '道具展示方式', exact: true })
  const toolList = toolSwitch.getByRole('button', { name: '列表', exact: true })
  const toolGrid = toolSwitch.getByRole('button', { name: '卡片', exact: true })
  const toolCatalog = page.locator('.product-catalog')
  await expect(toolList).toHaveAttribute('aria-pressed', 'true')
  await expect(toolCatalog).toHaveClass(/is-list/)
  await expect(page.locator('.product-list-header span')).toHaveText(['道具名称', '所属公司', '使用类别', '制作状态'])
  const toolRow = page.locator('.catalog-item')
  await expect(toolRow).toContainText('布局验收道具')
  await expect(toolRow).toContainText('主动')
  await expect(toolRow).toContainText('设计中')
  await expect(toolRow.getByRole('link', { name: '布局验收道具', exact: true })).toHaveAttribute('href', `/tools/${tool.id}`)
  await page.screenshot({ path: '/tmp/com-tools-list-desktop.png', fullPage: true })
  await toolGrid.click()
  await expect(toolCatalog).toHaveClass(/is-grid/)
  await expect(toolCatalog).toContainText('布局验收效果')
  await expect(toolCatalog).toContainText('购买')
  await page.reload()
  await expect(toolGrid).toHaveAttribute('aria-pressed', 'true')
  await toolList.click()
  await page.reload()
  await expect(toolList).toHaveAttribute('aria-pressed', 'true')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.product-list-header')).toBeHidden()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '/tmp/com-tools-list-mobile.png', fullPage: true })

  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/recipes')
  const recipeSwitch = page.getByRole('group', { name: '配方展示方式', exact: true })
  const recipeList = recipeSwitch.getByRole('button', { name: '列表', exact: true })
  const recipeGrid = recipeSwitch.getByRole('button', { name: '卡片', exact: true })
  const recipeCatalog = page.locator('.product-catalog')
  await expect(recipeList).toHaveAttribute('aria-pressed', 'true')
  await expect(recipeCatalog).toHaveClass(/is-list/)
  await expect(page.locator('.product-list-header span')).toHaveText(['产物名称', '类型', '配方数量', '制作状态'])
  const recipeRow = page.locator('.recipe-catalog-item')
  await expect(recipeRow).toContainText('布局验收产物')
  await expect(recipeRow).toContainText('商品')
  await expect(recipeRow).toContainText('0 套配方')
  await expect(recipeRow).toContainText('待补充')
  await expect(recipeRow).toContainText('制作中')
  await expect(recipeRow.getByRole('link', { name: '布局验收产物', exact: true })).toHaveAttribute('href', `/recipes/${group.id}`)
  await page.screenshot({ path: '/tmp/com-recipes-list-desktop.png', fullPage: true })
  await recipeGrid.click()
  await expect(recipeCatalog).toHaveClass(/is-grid/)
  await expect(recipeCatalog).toContainText('待补充')
  await page.reload()
  await expect(recipeGrid).toHaveAttribute('aria-pressed', 'true')
  await recipeList.click()
  await page.reload()
  await expect(recipeList).toHaveAttribute('aria-pressed', 'true')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.product-list-header')).toBeHidden()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '/tmp/com-recipes-list-mobile.png', fullPage: true })
})

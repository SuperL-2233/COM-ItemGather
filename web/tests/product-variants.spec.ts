import { test, expect, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/login')
  await page.getByLabel('用户名').fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('e2e-admin-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/ideas$/)
  return { 'X-CSRF-Token': (await (await page.request.get('/api/auth/me')).json()).csrf_token }
}

test('一次创建多款，按商品折叠、按口味搜索，并共用基础资料', async ({ page }) => {
  await login(page)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/products')
  await page.getByRole('button', { name: '创建商品', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '创建商品', exact: true })
  await dialog.getByLabel('商品中文名（可留空）').fill('变体验收咕噜牛奶')
  await dialog.getByLabel('描述', { exact: true }).fill('三款共用同一个瓶子模型')
  for (const [index, name] of ['原味', '草莓味', '巧克力味'].entries()) {
    await dialog.getByRole('button', { name: '添加口味／样式', exact: true }).click()
    await dialog.getByRole('textbox', { name: `第${index + 1}款口味／样式`, exact: true }).fill(name)
  }
  await dialog.getByRole('textbox', { name: '第2款差异说明', exact: true }).fill('粉色贴图')
  await dialog.getByRole('button', { name: '第1款制作状态', exact: true }).click()
  await dialog.getByRole('option', { name: '已完成', exact: true }).click()
  const created = page.waitForResponse(response => response.url().endsWith('/api/products') && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: '创建商品', exact: true }).click()
  const response = await created
  expect(response.ok(), await response.text()).toBeTruthy()
  const product = await response.json()
  expect(product.variant_count).toBe(3)
  expect(new Set(product.variants.map((item: { id: string }) => item.id)).size).toBe(3)
  await expect(dialog).toHaveCount(0)
  await page.getByRole('searchbox', { name: '搜索商品', exact: true }).fill('变体验收咕噜牛奶')
  await expect(page.locator('.catalog-item')).toHaveCount(1)
  await expect(page.locator('.catalog-group')).toContainText('3 款口味／样式')
  await expect(page.locator('.catalog-group')).toContainText('2 种制作状态')
  await page.getByRole('button', { name: '展开变体验收咕噜牛奶的口味／样式', exact: true }).click()
  await expect(page.locator('.catalog-group-members li')).toHaveCount(3)
  await page.screenshot({ path: '/tmp/com-product-variants-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '卡片', exact: true }).click()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: '/tmp/com-product-variants-mobile.png', fullPage: true })
  await page.getByRole('searchbox', { name: '搜索商品', exact: true }).fill('草莓味')
  await expect(page.locator('.catalog-group')).toContainText('匹配：草莓味')
  await page.locator('.catalog-group-members').getByRole('link', { name: '草莓味', exact: true }).click()
  await expect(page.getByRole('heading', { name: '变体验收咕噜牛奶 · 草莓味', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: '商品共用资料', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: '当前款设定', exact: true })).toBeVisible()
  await expect(page.getByLabel('当前款口味／样式（可留空）', { exact: true })).toHaveValue('草莓味')
  await expect(page.getByLabel('当前款差异说明', { exact: true })).toHaveValue('粉色贴图')
  await page.getByLabel('商品中文名', { exact: true }).fill('变体验收新牛奶')
  await page.getByRole('button', { name: '保存修改', exact: true }).click()
  await expect(page.getByRole('button', { name: '已保存', exact: true })).toBeVisible()
  for (const member of product.variants) {
    const current = await (await page.request.get(`/api/products/${member.id}`)).json()
    expect(current.chinese_name).toBe('变体验收新牛奶')
    expect(current.variant_name).toBe(member.variant_name)
    expect(current.development_status).toBe(member.development_status)
  }
  await page.getByRole('link', { name: '← 返回商品库', exact: true }).click()
  await expect(page.locator('.catalog-group-members li')).toHaveCount(3)
  await page.locator('.catalog-group-members').getByRole('link', { name: '草莓味', exact: true }).click()
  await page.getByRole('button', { name: '新增另一款', exact: true }).click()
  await page.getByLabel('另一款口味／样式', { exact: true }).fill('香蕉味')
  await expect(page.getByLabel('当前款口味／样式（可留空）', { exact: true })).toHaveValue('草莓味')
  await page.getByRole('button', { name: '保存新款', exact: true }).click()
  await expect(page.locator('.variant-members li')).toHaveCount(4)
  await expect(page.getByLabel('当前款口味／样式（可留空）', { exact: true })).toHaveValue('草莓味')
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: '/tmp/com-product-variants-detail-mobile.png', fullPage: true })
  await page.goto('/items/mind-map')
  await page.getByRole('searchbox', { name: '搜索导图', exact: true }).fill('变体验收新牛奶')
  await expect(page.locator('.mind-map-item')).toHaveCount(1)
  await expect(page.locator('.mind-map-item')).toContainText('4 款口味／样式')
  // Recipe selection still identifies a concrete item, including its flavor.
  await page.goto('/recipes')
  await page.getByRole('button', { name: '添加合成产物', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择合成产物', exact: true })
  await picker.getByRole('searchbox', { name: '搜索物品', exact: true }).fill('变体验收新牛奶')
  await expect(picker.locator('.choice-row')).toHaveCount(4)
  await expect(picker.locator('.choice-row').filter({ hasText: '草莓味' })).toHaveCount(1)
})

test('已有商品手动归组和移出时保留原物品 ID 与配方', async ({ page }) => {
  const headers = await login(page)
  const base = await (await page.request.post('/api/products', { headers, data: { chinese_name: '归组验收牛奶', description: '共用瓶子' } })).json()
  const legacy = await (await page.request.post('/api/products', { headers, data: { chinese_name: '归组验收旧草莓牛奶', variant_description: '粉色旧贴图' } })).json()
  const recipe = await (await page.request.post('/api/recipe-groups', { headers, data: { output_id: legacy.id } })).json()
  await page.goto(`/products/${legacy.id}`)
  await page.getByText('整理已有商品', { exact: true }).click()
  await page.getByRole('button', { name: '归入已有商品', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择要归入的商品', exact: true })
  await expect(picker.getByRole('button', { name: /▸ 道具/ })).toHaveCount(0)
  await picker.getByRole('searchbox', { name: '搜索物品', exact: true }).fill(base.chinese_name)
  await picker.locator('.choice-row').filter({ hasText: base.chinese_name }).click()
  await page.getByLabel('当前款归组后的口味／样式', { exact: true }).fill('草莓味')
  await page.getByRole('button', { name: '确认归组', exact: true }).click()
  await expect(page.getByRole('heading', { name: '归组验收牛奶 · 草莓味', exact: true })).toBeVisible()
  await expect(page).toHaveURL(new RegExp(`/products/${legacy.id}$`))
  await expect(page.locator('.variant-members li')).toHaveCount(2)
  const current = await (await page.request.get(`/api/products/${legacy.id}`)).json()
  expect(current.variant_group_id).toBe(base.variant_group_id)
  expect(current.variant_description).toBe('粉色旧贴图')
  expect((await (await page.request.get(`/api/recipe-groups/${recipe.id}`)).json()).output_id).toBe(legacy.id)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '将当前款移出分组', exact: true }).click()
  await expect(page.locator('.variant-members li')).toHaveCount(1)
  const detached = await (await page.request.get(`/api/products/${legacy.id}`)).json()
  expect(detached.id).toBe(legacy.id)
  expect(detached.variant_group_id).not.toBe(base.variant_group_id)
  expect(detached.description).toBe('共用瓶子')
})

import { test, expect, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

async function login(page: Page) {
  await page.goto('/login')
  await page.getByLabel('用户名').fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('e2e-admin-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/ideas$/)
  return { 'X-CSRF-Token': (await (await page.request.get('/api/auth/me')).json()).csrf_token }
}

async function noOverflow(page: Page) {
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
}

test('白鲸袋装奶下的三个口味同级管理，商品本身不代表任何一个口味', async ({ page }) => {
  const headers = await login(page)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/products')
  await page.getByRole('button', { name: '创建商品', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '创建商品', exact: true })
  await dialog.getByLabel('商品中文名（可留空）').fill('白鲸 袋装奶')
  await dialog.getByLabel('描述', { exact: true }).fill('三个口味共用袋装奶模型')
  for (const [index, name] of ['玫瑰荔枝味', '草莓味', '巧克力味'].entries()) {
    await dialog.getByRole('button', { name: '添加口味／样式', exact: true }).click()
    await dialog.getByRole('textbox', { name: `第${index + 1}款口味／样式`, exact: true }).fill(name)
  }
  await dialog.getByRole('textbox', { name: '第2款差异说明', exact: true }).fill('草莓粉色贴图')
  const created = page.waitForResponse(response => response.url().endsWith('/api/products') && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: '创建商品', exact: true }).click()
  const response = await created
  expect(response.ok(), await response.text()).toBeTruthy()
  const parent = await response.json()
  expect(parent.variant_name).toBe('')
  expect(parent.parent_product_id).toBe('')
  expect(parent.variants).toHaveLength(3)
  for (const child of parent.variants) { expect(child.parent_product_id).toBe(parent.id); expect(child.id).not.toBe(parent.id) }
  await expect(dialog).toHaveCount(0)
  await page.getByRole('searchbox', { name: '搜索商品', exact: true }).fill('白鲸 袋装奶')
  await expect(page.locator('.catalog-item')).toHaveCount(1)
  await expect(page.locator('.catalog-group')).toContainText('3 种口味／样式')
  await page.getByRole('button', { name: '展开白鲸 袋装奶的口味／样式', exact: true }).click()
  await expect(page.locator('.catalog-group-members li')).toHaveCount(3)
  await page.locator('.catalog-group-members').getByRole('link', { name: '草莓味', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`/products/${parent.id}#variant-`))
  await expect(page.getByRole('heading', { name: '白鲸 袋装奶', exact: true })).toBeVisible()
  await expect(page.locator('.record-form input[placeholder="例如：草莓味、蓝色款"]')).toHaveCount(0)
  await expect(page.locator('.record-form')).not.toContainText('口味／样式')
  await expect(page.getByText('当前款设定', { exact: true })).toHaveCount(0)
  await expect(page.getByText('本商品的全部款式', { exact: true })).toHaveCount(0)
  const panel = page.locator('.variants-panel')
  await expect(panel.getByRole('heading', { name: '商品口味／样式', exact: true })).toBeVisible()
  await expect(panel.locator('.product-variant > .variant-heading > h3')).toHaveText(['玫瑰荔枝味', '草莓味', '巧克力味'])
  const strawberry = panel.getByRole('article', { name: '草莓味', exact: true })
  await strawberry.getByRole('button', { name: '编辑', exact: true }).click()
  await strawberry.getByLabel('口味／样式名称', { exact: true }).fill('草莓酸奶味')
  await strawberry.getByLabel('差异说明', { exact: true }).fill('更新后的粉色贴图')
  await strawberry.getByRole('button', { name: '保存口味／样式', exact: true }).click()
  await expect(panel.getByRole('article', { name: '草莓酸奶味', exact: true })).toContainText('更新后的粉色贴图')
  await expect(page.getByRole('heading', { name: '白鲸 袋装奶', exact: true })).toBeVisible()
  await panel.getByRole('button', { name: '添加口味／样式', exact: true }).click()
  await panel.locator('.variant-add').getByLabel('口味／样式名称', { exact: true }).fill('香蕉味')
  await panel.locator('.variant-add').getByRole('button', { name: '添加', exact: true }).click()
  await expect(panel.locator('.product-variant')).toHaveCount(4)
  page.once('dialog', dialog => dialog.accept())
  await panel.getByRole('article', { name: '香蕉味', exact: true }).getByRole('button', { name: '删除', exact: true }).click()
  await expect(panel.locator('.product-variant')).toHaveCount(3)
  await page.getByLabel('商品中文名', { exact: true }).fill('白鲸 新袋装奶')
  await page.getByRole('button', { name: '保存修改', exact: true }).click()
  await expect(page.getByRole('button', { name: '已保存', exact: true })).toBeVisible()
  for (const child of parent.variants) {
    const current = await (await page.request.get(`/api/products/${child.id}`)).json()
    expect(current.chinese_name).toBe('白鲸 新袋装奶')
    expect(current.parent_product_id).toBe(parent.id)
  }
  for (const width of [390, 320]) { await page.setViewportSize({ width, height: 844 }); await noOverflow(page) }
  await page.screenshot({ path: '/tmp/com-product-flavors-hierarchy-mobile.png', fullPage: true })
  await page.goto('/items/mind-map')
  await page.getByRole('searchbox', { name: '搜索导图', exact: true }).fill('草莓酸奶味')
  await expect(page.locator('.mind-map-item')).toHaveCount(1)
  await expect(page.locator('.mind-map-item')).toContainText('白鲸 新袋装奶')
  await expect(page.locator('.mind-map-item')).toContainText('3 种口味／样式')
  await page.goto('/recipes')
  await page.getByRole('button', { name: '添加合成产物', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择合成产物', exact: true })
  await picker.getByRole('searchbox', { name: '搜索物品', exact: true }).fill('白鲸 新袋装奶')
  await expect(picker.locator('.choice-row')).toHaveCount(4)
  await expect(picker.locator('.picker-variants .choice-row')).toHaveCount(3)
  await expect(picker.locator('.picker-variants .choice-row strong')).toHaveText(['玫瑰荔枝味', '草莓酸奶味', '巧克力味'])
  const childID = parent.variants[1].id
  const groupResponse = await page.request.post('/api/recipe-groups', { headers, data: { output_id: childID } })
  expect(groupResponse.ok()).toBeTruthy()
  const group = await groupResponse.json()
  expect(group.output_id).toBe(childID)
})

test('没有口味和只有一个口味时仍是父商品，口味图片和旧链接保留', async ({ page }) => {
  const headers = await login(page)
  const response = await page.request.post('/api/products', { headers, data: { chinese_name: '白鲸 纯牛奶', development_status: 'completed' } })
  expect(response.ok()).toBeTruthy()
  const parent = await response.json()
  await page.goto(`/products/${parent.id}`)
  const panel = page.locator('.variants-panel')
  await expect(panel.locator('.product-variant')).toHaveCount(0)
  await expect(panel).toContainText('尚未添加口味／样式')
  await panel.getByRole('button', { name: '添加口味／样式', exact: true }).click()
  await panel.locator('.variant-add').getByLabel('口味／样式名称', { exact: true }).fill('香草味')
  await panel.locator('.variant-add').getByRole('button', { name: '添加', exact: true }).click()
  await expect(panel.locator('.product-variant')).toHaveCount(1)
  await expect(page.getByRole('heading', { name: '白鲸 纯牛奶', exact: true })).toBeVisible()
  const root = await (await page.request.get(`/api/products/${parent.id}`)).json()
  expect(root.variant_name).toBe('')
  expect(root.development_status).toBe('completed')
  const child = root.variants[0]
  const card = panel.getByRole('article', { name: '香草味', exact: true })
  await card.getByRole('button', { name: '编辑', exact: true }).click()
  await card.locator('input[type="file"]').setInputFiles({ name: 'vanilla.png', mimeType: 'image/png', buffer: readFileSync('public/icon-192.png') })
  await expect(card.locator('.attachment-grid img')).toHaveCount(1)
  const savedChild = await (await page.request.get(`/api/products/${child.id}`)).json()
  expect(savedChild.attachments).toHaveLength(1)
  expect((await (await page.request.get(`/api/products/${parent.id}`)).json()).attachments).toHaveLength(0)
  await card.getByRole('button', { name: '取消编辑', exact: true }).click()
  await page.goto(`/products/${child.id}`)
  await expect(page).toHaveURL(new RegExp(`/products/${parent.id}#variant-${child.id}$`))
  await expect(page.getByRole('heading', { name: '白鲸 纯牛奶', exact: true })).toBeVisible()
  await expect(page.locator('.product-variant')).toHaveCount(1)
  await expect(page.getByRole('article', { name: '香草味', exact: true }).locator('.variant-images img')).toHaveCount(1)
})

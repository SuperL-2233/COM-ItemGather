import { test, expect, type Page } from '@playwright/test'

async function login(page: Page,member = false) {
  await page.goto('/login')
  await page.getByLabel('用户名').fill(member ? 'member' : 'admin')
  await page.getByLabel('密码',{ exact: true }).fill(member ? 'e2e-member-password' : 'e2e-admin-password')
  await page.getByRole('button',{ name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/ideas$/)
}
async function post(page: Page,path: string,data: object) {
  const me = await (await page.request.get('/api/auth/me')).json()
  const response = await page.request.post(`/api/${path}`,{ headers: { 'X-CSRF-Token': me.csrf_token }, data })
  expect(response.ok(),await response.text()).toBeTruthy()
  return response.json()
}
async function openDelete(page: Page,name: string) {
  const manager = await page.context().newPage()
  await manager.goto('/settings/options?kind=categories')
  await manager.getByRole('button', { name: `删除分类“${name}”`, exact: true }).click()
  const dialog = manager.getByRole('dialog', { name: `删除分类“${name}”`, exact: true })
  await expect(dialog.getByText('商品、道具和配方本身都会保留。', { exact: true })).toBeVisible()
  return dialog
}

test('设置页分类可键盘删除、取消，并保留其他标签页的新建商品草稿',async ({ page }) => {
  await login(page)
  const name = '可删除的空类别'
  await post(page,'product-options/categories',{ name })
  await page.goto('/products')
  await page.getByRole('button',{ name: '创建商品', exact: true }).click()
  const form = page.getByRole('dialog',{ name: '创建商品', exact: true })
  await form.getByLabel('商品中文名（可留空）').fill('删除分类后保留的草稿')
  await form.getByLabel('描述',{ exact: true }).fill('保留商品说明')
  await form.getByRole('button',{ name: '商品分类', exact: true }).click()
  await form.getByRole('combobox',{ name: '搜索商品分类', exact: true }).fill(name)
  await form.getByRole('option',{ name, exact: true }).click()
  let dialog = await openDelete(page,name)
  await dialog.getByRole('button',{ name: '取消', exact: true }).click()
  await expect(form.getByRole('button',{ name: '商品分类', exact: true })).toContainText(name)
  const manager = dialog.page()
  const remove = manager.getByRole('button', { name: `删除分类“${name}”`, exact: true })
  await expect(remove).toBeFocused()
  await remove.press('Enter')
  dialog = manager.getByRole('dialog', { name: `删除分类“${name}”`, exact: true })
  await expect(dialog).toContainText('此分类当前未被使用')
  await dialog.getByRole('button',{ name: '确认删除分类', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(form).toBeVisible()
  await expect(form.getByText('该分类已被删除，请重新选择。', { exact: true })).toBeVisible()
  await form.getByRole('button', { name: '商品分类', exact: true }).click()
  await form.getByRole('option', { name: '未设置商品分类', exact: true }).click()
  await expect(form.getByRole('button', { name: '商品分类', exact: true })).toContainText('未设置商品分类')
  await expect(form.getByLabel('描述',{ exact: true })).toHaveValue('保留商品说明')
  await form.getByRole('button',{ name: '制作状态', exact: true }).click()
  await expect(form.getByRole('button',{ name: /^删除分类/ })).toHaveCount(0)
  await form.getByRole('combobox',{ name: '搜索制作状态', exact: true }).press('Escape')
  await form.getByRole('button',{ name: '创建商品', exact: true }).click()
  await page.getByRole('link',{ name: '删除分类后保留的草稿', exact: true }).click()
  await expect(page).toHaveURL(/\/products\/[a-f0-9-]+$/)
  await expect(page.getByRole('button',{ name: '商品分类', exact: true })).toContainText('未设置商品分类')
  const options = await (await page.request.get('/api/product-options/categories')).json()
  expect(options.items.some((item: {value:string}) => item.value === name)).toBeFalsy()
})

test('使用中的分类可替换，其他成员草稿不会覆盖删除结果',async ({ page,browser }) => {
  await login(page)
  const name = '需要替换的商品类别';const target = '替换后的商品类别'
  const item = await post(page,'products',{ chinese_name: '分类替换验收商品',category: name })
  await post(page,'product-options/categories',{ name: target })
  await page.goto(`/products/${item.id}`)
  const context = await browser.newContext()
  try {
    const second = await context.newPage()
    await login(second,true)
    await second.goto(`/products/${item.id}`)
    await second.getByLabel('商品描述',{ exact: true }).fill('其他成员的未保存说明')
    const dialog = await openDelete(page,name)
    await dialog.getByRole('radio',{ name: '替换为其他分类', exact: true }).check()
    await dialog.getByRole('button',{ name: '替代分类', exact: true }).click()
    await dialog.getByRole('combobox',{ name: '搜索替代分类', exact: true }).fill(target)
    await expect(dialog.getByRole('button',{ name: /^删除分类/ })).toHaveCount(0)
    await dialog.getByRole('option',{ name: target, exact: true }).click()
    await dialog.getByRole('button',{ name: '确认删除分类', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.getByRole('button',{ name: '商品分类', exact: true })).toContainText(target)
    await expect(page.getByRole('button',{ name: '已保存', exact: true })).toBeVisible()
    await expect(second.getByText('该分类已被删除，请重新选择。',{ exact: true })).toBeVisible()
    await expect(second.getByLabel('商品描述',{ exact: true })).toHaveValue('其他成员的未保存说明')
    await second.getByRole('button',{ name: '商品分类', exact: true }).click()
    await second.getByRole('combobox',{ name: '搜索商品分类', exact: true }).fill(target)
    await second.getByRole('option',{ name: target, exact: true }).click()
    await second.getByRole('button',{ name: '保存修改', exact: true }).click()
    await expect(second.getByRole('dialog',{ name: '检测到同时编辑', exact: true })).toBeVisible()
    await second.getByRole('button',{ name: '将我的修改应用到最新版', exact: true }).click()
    await expect(second.getByRole('button',{ name: '已保存', exact: true })).toBeVisible()
    const result = await (await second.request.get(`/api/products/${item.id}`)).json()
    expect(result.category).toBe(target)
    expect(result.description).toBe('其他成员的未保存说明')
  } finally { await context.close() }
})

test('配方分类删除要求替代类别，并发变化需重新确认且合并材料数量',async ({ page }) => {
  await login(page)
  const name = '待删除配方材料类';const target = '配方替代材料类'
  await post(page,'product-options/categories',{ name })
  await post(page,'product-options/categories',{ name: target })
  const item = await post(page,'products',{ chinese_name: '配方分类删除产物' })
  const group = await post(page,'recipe-groups',{ output_id: item.id })
  await post(page,`recipe-groups/${group.id}/recipes`,{ output_quantity: 1,ingredients: [{category: name,quantity: 2},{category: target,quantity: 3}] })
  await page.goto(`/products/${item.id}`)
  const dialog = await openDelete(page,name)
  await expect(dialog.getByRole('radio',{ name: '清空关联物品的分类', exact: true })).toBeDisabled()
  await expect(dialog.getByRole('button',{ name: '确认删除分类', exact: true })).toBeDisabled()
  await dialog.getByRole('button',{ name: '替代分类', exact: true }).click()
  await dialog.getByRole('combobox',{ name: '搜索替代分类', exact: true }).fill(target)
  await dialog.getByRole('option',{ name: target, exact: true }).click()
  await post(page,`recipe-groups/${group.id}/recipes`,{ output_quantity: 1,ingredients: [{category: name,quantity: 1}] })
  await dialog.getByRole('button',{ name: '确认删除分类', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('分类使用情况已变化')
  await expect(dialog).toContainText('2 套配方')
  await dialog.page().setViewportSize({ width: 390,height: 844 })
  await dialog.page().screenshot({ path: '/tmp/com-category-delete-mobile.png' })
  await dialog.getByRole('button',{ name: '确认删除分类', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const result = await (await page.request.get(`/api/recipe-groups/${group.id}`)).json()
  expect(result.recipes[0].ingredients).toHaveLength(1)
  expect(result.recipes[0].ingredients[0].category).toBe(target)
  expect(result.recipes[0].ingredients[0].quantity).toBe(5)
  expect(result.recipes[1].ingredients[0].category).toBe(target)
})

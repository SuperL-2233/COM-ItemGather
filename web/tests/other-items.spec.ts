test('合成配方可选取其他物品作为产物和材料，保存刷新后保留物品与数量', async ({ page }) => {
  await login(page)
  const output = await post(page, 'other-items', { chinese_name: '配方选取验收产物', english_name: 'Recipe Other Output' })
  const material = await post(page, 'other-items', { chinese_name: '配方选取验收材料', english_name: 'Recipe Other Material' })
  await page.goto('/recipes')
  await page.getByRole('button', { name: '添加合成产物', exact: true }).click()
  const outputPicker = page.getByRole('dialog', { name: '选择合成产物', exact: true })
  const otherGroup = outputPicker.locator('.picker-group-toggle').filter({ hasText: '其他物品' })
  await expect(otherGroup).toContainText(/[1-9]\d*/)
  await expect(otherGroup).toHaveAttribute('aria-expanded', 'false')
  await otherGroup.click()
  await outputPicker.locator('.choice-row').filter({ hasText: output.chinese_name }).click()
  await expect(page).toHaveURL(/\/recipes\/[a-f0-9-]+$/)
  const groupId = new URL(page.url()).pathname.split('/').at(-1)!
  await expect(page.getByRole('heading', { name: output.chinese_name, exact: true })).toBeVisible()
  await page.getByRole('button', { name: '＋ 添加配方', exact: true }).click()
  const editor = page.locator('.recipe-editor').first()
  await editor.getByLabel('配方名称（可留空）', { exact: true }).fill('其他物品选取验收配方')
  await editor.getByRole('button', { name: '＋ 添加材料', exact: true }).click()
  const materialPicker = page.getByRole('dialog', { name: '选择材料', exact: true })
  await materialPicker.getByRole('searchbox', { name: '搜索物品', exact: true }).fill(material.english_name)
  await expect(materialPicker.locator('.picker-group-toggle').filter({ hasText: '其他物品' })).toHaveAttribute('aria-expanded', 'true')
  await materialPicker.locator('.choice-row').filter({ hasText: material.chinese_name }).click()
  await expect(materialPicker).toHaveCount(0)
  await expect(editor.locator('.ingredient-row')).toContainText('其他物品')
  await editor.getByLabel('材料 1 数量', { exact: true }).fill('4')
  await editor.getByRole('button', { name: '保存这套配方', exact: true }).click()
  await expect(editor.getByRole('button', { name: '已保存', exact: true })).toBeVisible()
  await page.reload()
  await expect(editor.locator('.recipe-summary')).toContainText(`${material.chinese_name} ×4`)
  await editor.locator('.recipe-summary').click()
  await expect(editor.locator('.ingredient-row')).toContainText(material.chinese_name)
  await expect(editor.getByLabel('材料 1 数量', { exact: true })).toHaveValue('4')
  const response = await page.request.get(`/api/recipe-groups/${groupId}`)
  expect(response.ok(), await response.text()).toBeTruthy()
  const saved = await response.json()
  expect(saved.output_id).toBe(output.id)
  expect(saved.output.item_kind).toBe('other')
  expect(saved.recipes[0].ingredients).toHaveLength(1)
  expect(saved.recipes[0].ingredients[0].product_id).toBe(material.id)
  expect(saved.recipes[0].ingredients[0].item.item_kind).toBe('other')
  expect(saved.recipes[0].ingredients[0].quantity).toBe(4)
})

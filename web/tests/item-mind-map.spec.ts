test('实时连接中断时定时校准数据，同步失败保留原图并可恢复', async ({ page }) => {
  await login(page)
  const company = await write(page.request, 'POST', 'companies', { chinese_name: '导图校准验收' })
  const goods = await write(page.request, 'POST', 'products', { chinese_name: '导图校准验收·商品', company_id: company.id })
  await page.clock.install()
  await page.route('**/api/events', route => route.abort())
  await page.goto('/items/mind-map')
  const companyFilter = page.getByLabel('导图所属公司', { exact: true })
  await expect(companyFilter.locator('option', { hasText: company.chinese_name })).toHaveCount(1)
  await companyFilter.selectOption(company.id)
  const node = page.locator(`[data-item-id="${goods.id}"]`)
  await expect(node).toHaveCSS('border-top-color', 'rgb(109, 113, 105)')
  await page.route('**/api/item-mind-map', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: '校准暂时不可用' } }) }))
  await page.clock.fastForward(15000)
  await expect(page.getByRole('alert')).toContainText('当前保留上次成功读取的导图')
  await expect(node).toHaveCSS('border-top-color', 'rgb(109, 113, 105)')
  await page.unroute('**/api/item-mind-map')
  await write(page.request, 'PATCH', `products/${goods.id}`, { version: goods.version, development_status: 'production' })
  await expect(node).toHaveCSS('border-top-color', 'rgb(109, 113, 105)')
  await page.clock.fastForward(15000)
  await expect(node).toHaveCSS('border-top-color', 'rgb(140, 97, 28)')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(companyFilter).toHaveValue(company.id)
  await page.reload()
  await expect(page.locator(`[data-item-id="${goods.id}"]`)).toHaveCSS('border-top-color', 'rgb(140, 97, 28)')
})

test.describe('手机触控导图', () => {
  test.use({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })

  test('双指围绕中点缩放、单指拖动、手势切换与取消后仍能点击商品', async ({ page }) => {
    await login(page)
    const company = await write(page.request, 'POST', 'companies', { chinese_name: '无公司', description: '明确不设置公司的商品归组' })
    let firstID = ''
    for (let index = 0; index < 10; index++) {
      const goods = await write(page.request, 'POST', 'products', { chinese_name: `双指缩放验收 ${String(index).padStart(2, '0')}`, company_id: company.id, category: '测试商品分类' })
      if (!index) firstID = goods.id
    }
    await page.goto('/items/mind-map')
    await page.getByLabel('导图所属公司', { exact: true }).selectOption(company.id)
    await expect(page.locator(`[data-company-id="${company.id}"]`)).toContainText('10 件商品')
    const viewport = page.getByRole('region', { name: '公司与商品思维导图', exact: true })
    const scale = page.getByLabel('导图缩放比例', { exact: true })
    await viewport.scrollIntoViewIfNeeded()
    await viewport.evaluate(element => { element.scrollLeft = 500; element.scrollTop = 180 })
    const bounds = (await viewport.boundingBox())!
    const width = await viewport.evaluate(element => element.clientWidth)
    const x = bounds.x + width / 2
    const y = bounds.y + 220
    const client = await page.context().newCDPSession(page)
    await client.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 2 })
    const touch = (type: 'touchStart' | 'touchMove' | 'touchEnd' | 'touchCancel', points: { id: number; x: number; y: number }[]) => client.send('Input.dispatchTouchEvent', { type, touchPoints: points.map(point => ({ ...point, radiusX: 2, radiusY: 2, force: 1 })) })
    const anchor = await viewport.evaluate((element, centerX) => ({ x: element.scrollLeft + centerX, y: element.scrollTop + 220 }), width / 2)
    await touch('touchStart', [{ id: 1, x: x - 40, y }, { id: 2, x: x + 40, y }])
    await touch('touchMove', [{ id: 1, x: x + 12 - 60, y: y + 16 }, { id: 2, x: x + 12 + 60, y: y + 16 }])
    await expect(scale).toHaveText('150%')
    const afterPinch = await viewport.evaluate((element, centerX) => ({ x: (element.scrollLeft + centerX + 12) / 1.5, y: (element.scrollTop + 236) / 1.5 }), width / 2)
    expect(Math.abs(afterPinch.x - anchor.x)).toBeLessThan(2)
    expect(Math.abs(afterPinch.y - anchor.y)).toBeLessThan(2)
    await touch('touchEnd', [])
    await expect(page).toHaveURL(/\/items\/mind-map$/)
    expect(await page.evaluate(() => visualViewport!.scale)).toBe(1)

    const beforePan = await viewport.evaluate(element => ({ left: element.scrollLeft, top: element.scrollTop }))
    await touch('touchStart', [{ id: 1, x: x + 50, y }])
    await touch('touchMove', [{ id: 1, x: x - 50, y: y - 60 }])
    await expect.poll(() => viewport.evaluate(element => element.scrollLeft)).toBeGreaterThan(beforePan.left + 80)
    await expect.poll(() => viewport.evaluate(element => element.scrollTop)).toBeGreaterThan(beforePan.top + 40)
    // A second finger can start a pinch without ending the ongoing pan.
    await touch('touchStart', [{ id: 1, x: x - 50, y: y - 60 }, { id: 2, x: x + 30, y: y - 60 }])
    await touch('touchMove', [{ id: 1, x: x - 30, y: y - 60 }, { id: 2, x: x + 10, y: y - 60 }])
    await expect(scale).toHaveText('75%')
    await touch('touchEnd', [])

    await touch('touchStart', [{ id: 1, x: x - 20, y }, { id: 2, x: x + 20, y }])
    await touch('touchMove', [{ id: 1, x: x - 100, y }, { id: 2, x: x + 100, y }])
    await expect(scale).toHaveText('175%')
    await touch('touchMove', [{ id: 1, x: x - 1, y }, { id: 2, x: x + 1, y }])
    await expect(scale).toHaveText('25%')
    await touch('touchCancel', [])
    await expect.poll(() => viewport.evaluate(element => element.scrollWidth <= element.clientWidth)).toBeTruthy()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.screenshot({ path: '/tmp/com-item-mind-map-touch-mobile.png', fullPage: true })
    await page.getByRole('button', { name: '重置视图', exact: true }).tap()
    await expect(scale).toHaveText('100%')
    await page.locator(`[data-item-id="${firstID}"]`).getByRole('link', { name: '双指缩放验收 00', exact: true }).tap()
    await expect(page).toHaveURL(new RegExp(`/products/${firstID}$`))
    await expect(page.getByLabel('商品中文名', { exact: true })).toHaveValue('双指缩放验收 00')
    await client.detach()
  })
})

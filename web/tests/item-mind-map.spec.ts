import { test, expect, type APIRequestContext, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/login')
  await page.getByLabel('用户名').fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('e2e-admin-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/ideas$/)
}

async function write(client: APIRequestContext, method: string, path: string, data: object) {
  const { csrf_token } = await (await client.get('/api/auth/me')).json()
  const response = await client.fetch(`/api/${path}`, { method, headers: { 'X-CSRF-Token': csrf_token }, data })
  expect(response.ok(), await response.text()).toBeTruthy()
  return response.json()
}


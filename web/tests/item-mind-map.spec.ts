test('其他成员修改归属、状态、公司及回收站后导图实时刷新并保留视图', async ({ page, request }) => {
  await login(page)
  const source = await write(page.request, 'POST', 'companies', { chinese_name: '导图实时验收·来源' })
  const target = await write(page.request, 'POST', 'companies', { chinese_name: '导图实时验收·目标' })
  const { option: custom } = await write(page.request, 'POST', 'product-options/statuses', { name: '导图实时待复核', color: '#345678' })
  const goods = await write(page.request, 'POST', 'products', { chinese_name: '导图实时验收·汽水', company_id: source.id })
  const tool = await write(page.request, 'POST', 'tools', { chinese_name: '导图实时验收·工具', company_id: target.id })
  const loggedIn = await request.post('/api/auth/login', { data: { username: 'member', password: 'e2e-member-password', remember: true } })
  expect(loggedIn.ok()).toBeTruthy()
  await page.goto('/items/mind-map')
  const search = page.getByRole('searchbox', { name: '搜索导图', exact: true })
  await search.fill('导图实时验收')
  const sourceBranch = page.locator(`[data-company-id="${source.id}"]`)
  const targetBranch = page.locator(`[data-company-id="${target.id}"]`)
  await expect(sourceBranch.locator('.mind-map-item')).toHaveCount(1)
  await sourceBranch.getByRole('button', { name: `折叠${source.chinese_name}`, exact: true }).click()
  await page.getByRole('button', { name: '缩小导图', exact: true }).click()
  await write(request, 'POST', 'products', { chinese_name: '导图实时验收·新商品', company_id: source.id })
  await expect(sourceBranch).toContainText('2 件物品')
  await expect(sourceBranch.locator('.mind-map-item')).toHaveCount(0)
  await expect(sourceBranch.getByRole('button', { name: `展开${source.chinese_name}`, exact: true })).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByLabel('导图缩放比例', { exact: true })).toHaveText('85%')
  await expect(search).toHaveValue('导图实时验收')
  await sourceBranch.getByRole('button', { name: `展开${source.chinese_name}`, exact: true }).click()

  await write(request, 'PATCH', `products/${goods.id}`, { version: goods.version, company_id: target.id, development_status: custom.value })
  const goodsNode = page.locator(`[data-item-id="${goods.id}"]`)
  await expect(targetBranch.locator(`[data-item-id="${goods.id}"]`)).toContainText(custom.label)
  await expect(sourceBranch.locator(`[data-item-id="${goods.id}"]`)).toHaveCount(0)
  await write(request, 'PATCH', `product-options/statuses/${custom.value}/color`, { version: custom.version, color: '#af32be' })
  await expect(goodsNode.locator('.status-badge')).toHaveAttribute('style', /#af32be/)
  await write(request, 'PATCH', `companies/${target.id}`, { version: target.version, chinese_name: '导图实时验收·已更名公司' })
  await expect(targetBranch.getByRole('link', { name: '导图实时验收·已更名公司', exact: true })).toBeVisible()
  await write(request, 'POST', `companies/${target.id}/merge`, { version: target.version + 1, target_id: source.id, target_version: source.version })
  await expect(targetBranch).toHaveCount(0)
  await expect(sourceBranch.locator('.mind-map-item')).toHaveCount(3)
  await expect(sourceBranch.locator(`[data-item-id="${tool.id}"]`)).toHaveCount(1)

  const current = await (await request.get(`/api/products/${goods.id}`)).json()
  const deleted = await write(request, 'DELETE', `products/${goods.id}`, { version: current.version })
  await expect(goodsNode).toHaveCount(0)
  await write(request, 'POST', `products/${goods.id}/restore`, { version: deleted.version })
  await expect(goodsNode).toContainText(custom.label)
  await page.getByLabel('导图制作状态', { exact: true }).selectOption(custom.value)
  const usage = await (await request.get(`/api/product-options/statuses/usage?id=${custom.value}`)).json()
  await write(request, 'DELETE', 'product-options/statuses', { id: custom.value, token: usage.token, replacement: 'completed' })
  await expect(page.getByLabel('导图制作状态', { exact: true })).toHaveValue('')
  await expect(goodsNode).toContainText('已完成')
  const other = await write(request, 'POST', 'other-items', { chinese_name: '导图实时验收·新线索' })
  await expect(page.locator(`[data-company-id="__unassigned__"] [data-item-id="${other.id}"]`)).toHaveCount(1)
})

test('实时连接中断时定时校准数据，同步失败保留原图并可恢复', async ({ page }) => {
  await login(page)
  const company = await write(page.request, 'POST', 'companies', { chinese_name: '导图校准验收' })
  const goods = await write(page.request, 'POST', 'products', { chinese_name: '导图校准验收·商品', company_id: company.id })
  await page.clock.install()
  await page.route('**/api/events', route => route.abort())
  await page.goto('/items/mind-map')
  const companyFilter = page.getByLabel('导图所属公司', { exact: true })
  await expect(companyFilter.locator('option', { hasText: company.chinese_name })).toHaveCount(1)
  await companyFilter.selectOption(company.id)
  const node = page.locator(`[data-item-id="${goods.id}"]`)
  await expect(node).toContainText('构思中')
  await page.route('**/api/item-mind-map', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: '校准暂时不可用' } }) }))
  await page.clock.fastForward(15000)
  await expect(page.getByRole('alert')).toContainText('当前保留上次成功读取的导图')
  await expect(node).toContainText('构思中')
  await page.unroute('**/api/item-mind-map')
  await write(page.request, 'PATCH', `products/${goods.id}`, { version: goods.version, development_status: 'production' })
  await expect(node).toContainText('构思中')
  await page.clock.fastForward(15000)
  await expect(node).toContainText('制作中')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(companyFilter).toHaveValue(company.id)
  await page.reload()
  await expect(page.locator(`[data-item-id="${goods.id}"]`)).toContainText('制作中')
})

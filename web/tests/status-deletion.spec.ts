import { test, expect, type Page } from '@playwright/test'

async function login(page: Page, member = false) {
  await page.goto('/login')
  await page.getByLabel('用户名').fill(member ? 'member' : 'admin')
  await page.getByLabel('密码', { exact: true }).fill(member ? 'e2e-member-password' : 'e2e-admin-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/ideas$/)
}
async function post(page: Page, path: string, data: object) {
  const { csrf_token } = await (await page.request.get('/api/auth/me')).json()
  const response = await page.request.post(`/api/${path}`, { headers: { 'X-CSRF-Token': csrf_token }, data })
  expect(response.ok(), await response.text()).toBeTruthy()
  return response.json()
}
async function openDelete(page: Page, name: string) {
  const manager = await page.context().newPage()
  await manager.goto('/settings/options?kind=statuses')
  await manager.getByRole('button', { name: `删除制作状态“${name}”`, exact: true }).click()
  const dialog = manager.getByRole('dialog', { name: `删除制作状态“${name}”`, exact: true })
  await expect(dialog).toBeVisible()
  return dialog
}

test('商品表单无品牌字段，设置页删除状态并保留创建草稿', async ({ page }) => {
  await login(page)
  const name = '未使用的临时制作阶段'
  await post(page, 'product-options/statuses', { name })
  await page.goto('/products')
  await page.getByRole('button', { name: '创建商品', exact: true }).click()
  const form = page.getByRole('dialog', { name: '创建商品', exact: true })
  await expect(form.getByLabel(/品牌名/)).toHaveCount(0)
  await expect(form.getByText(/最终展示/)).toHaveCount(0)
  await form.getByLabel('商品中文名（可留空）').fill('色乐青苹果汽水')
  await form.getByLabel('商品英文名（可留空）').fill('Color Green Apple Soda')
  await form.getByLabel('描述', { exact: true }).fill('删除状态时应保留的草稿说明')
  await form.getByRole('button', { name: '制作状态', exact: true }).click()
  await form.getByRole('combobox', { name: '搜索制作状态', exact: true }).fill(name)
  await form.getByRole('option', { name, exact: true }).click()
  let dialog = await openDelete(page, name)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  const manager = dialog.page()
  const remove = manager.getByRole('button', { name: `删除制作状态“${name}”`, exact: true })
  await expect(remove).toBeFocused()
  await expect(form.getByRole('button', { name: '制作状态', exact: true })).toContainText(name)
  await remove.press('Enter')
  dialog = manager.getByRole('dialog', { name: `删除制作状态“${name}”`, exact: true })
  await expect(dialog).toContainText('此状态当前未被使用')
  await dialog.getByRole('button', { name: '确认删除制作状态', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(form.getByText('该制作状态已被删除，请重新选择。', { exact: true })).toBeVisible()
  await form.getByRole('button', { name: '制作状态', exact: true }).click()
  await form.getByRole('option', { name: '构思中', exact: true }).click()
  await expect(form.getByRole('button', { name: '制作状态', exact: true })).toContainText('构思中')
  await expect(form.getByLabel('描述', { exact: true })).toHaveValue('删除状态时应保留的草稿说明')
  const created = page.waitForResponse(response => response.url().endsWith('/api/products') && response.request().method() === 'POST')
  await form.getByRole('button', { name: '创建商品', exact: true }).click()
  const response = await created
  expect(response.ok()).toBeTruthy()
  expect(response.request().postDataJSON()).not.toHaveProperty('brand_name')
  const item = await response.json()
  expect(item).not.toHaveProperty('brand_name')
  await page.getByRole('link', { name: '色乐青苹果汽水', exact: true }).click()
  await expect(page.getByLabel(/品牌名/)).toHaveCount(0)
  await expect(page.getByText(/最终展示/)).toHaveCount(0)
  await expect(page.getByLabel('商品中文名', { exact: true })).toHaveValue('色乐青苹果汽水')
  await page.screenshot({ path: '/tmp/com-product-without-brand.png', fullPage: true })
})

test('状态删除需确认最新使用情况，替换商品与配方并保留其他成员草稿', async ({ page, browser }) => {
  await login(page)
  const name = '准备删除的复核阶段'
  const target = '统一替代制作阶段'
  const state = (await post(page, 'product-options/statuses', { name })).option
  const replacement = (await post(page, 'product-options/statuses', { name: target })).option
  const item = await post(page, 'products', { chinese_name: '状态删除协作验收商品', development_status: state.value })
  const group = await post(page, 'recipe-groups', { output_id: item.id })
  await post(page, `recipe-groups/${group.id}/recipes`, { output_quantity: 1, development_status: state.value, ingredients: [] })
  await page.goto(`/products/${item.id}`)
  const context = await browser.newContext()
  try {
    const second = await context.newPage()
    await login(second, true)
    await second.goto(`/products/${item.id}`)
    await second.getByLabel('商品描述', { exact: true }).fill('其他成员尚未保存的说明')
    const library = await context.newPage()
    await library.goto('/products')
    await library.getByRole('searchbox', { name: '搜索商品', exact: true }).fill('状态删除协作验收商品')
    await library.getByRole('button', { name: '筛选商品', exact: true }).click()
    const filters = library.getByRole('dialog', { name: '商品筛选', exact: true })
    await filters.getByRole('navigation').getByRole('button', { name: '制作状态', exact: true }).click()
    await filters.locator('.filter-options-pane').getByRole('button', { name, exact: true }).click()
    await filters.getByRole('button', { name: '完成', exact: true }).click()
    await expect(library.locator('.product-card')).toHaveCount(1)
    const dialog = await openDelete(page, name)
    await expect(dialog).toContainText('1 件物品、1 套配方')
    await expect(dialog.getByRole('button', { name: '确认删除制作状态', exact: true })).toBeDisabled()
    await dialog.getByRole('button', { name: '替代状态', exact: true }).click()
    await dialog.getByRole('combobox', { name: '搜索替代状态', exact: true }).fill(target)
    await dialog.getByRole('option', { name: target, exact: true }).click()
    await post(page, 'tools', { chinese_name: '确认期间新增的道具', development_status: state.value })
    await dialog.getByRole('button', { name: '确认删除制作状态', exact: true }).click()
    await expect(dialog.getByRole('alert')).toContainText('制作状态使用情况已变化')
    await expect(dialog).toContainText('2 件物品、1 套配方')
    await dialog.page().setViewportSize({ width: 390, height: 844 })
    await expect.poll(() => dialog.page().evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
    await dialog.page().screenshot({ path: '/tmp/com-status-delete-mobile.png' })
    await dialog.getByRole('button', { name: '确认删除制作状态', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.getByRole('button', { name: '制作状态', exact: true })).toContainText(target)
    await expect(page.getByRole('button', { name: '已保存', exact: true })).toBeVisible()
    await expect(library.locator('.product-active-filters')).toHaveCount(0)
    await expect(library.locator('.product-card')).toHaveCount(1)
    await expect(library.locator('.product-card')).toContainText(target)
    await expect(library.locator('.error-text')).toHaveCount(0)
    await expect(second.getByText('该制作状态已被删除，请重新选择。', { exact: true })).toBeVisible()
    await expect(second.getByLabel('商品描述', { exact: true })).toHaveValue('其他成员尚未保存的说明')
    await second.getByRole('button', { name: '制作状态', exact: true }).click()
    await second.getByRole('combobox', { name: '搜索制作状态', exact: true }).fill(target)
    await second.getByRole('option', { name: target, exact: true }).click()
    await second.getByRole('button', { name: '保存修改', exact: true }).click()
    await expect(second.getByRole('dialog', { name: '检测到同时编辑', exact: true })).toBeVisible()
    await second.getByRole('button', { name: '将我的修改应用到最新版', exact: true }).click()
    await expect(second.getByRole('button', { name: '已保存', exact: true })).toBeVisible()
    const result = await (await second.request.get(`/api/products/${item.id}`)).json()
    expect(result.development_status).toBe(replacement.value)
    expect(result.description).toBe('其他成员尚未保存的说明')
    await page.goto(`/recipes/${group.id}`)
    await expect(page.getByRole('button', { name: '制作状态', exact: true })).toContainText(target)
  } finally { await context.close() }
})

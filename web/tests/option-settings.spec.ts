import { test, expect, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/login')
  await page.getByLabel('用户名').fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('e2e-admin-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/ideas$/)
}
async function add(page: Page, noun: string, name: string) {
  await page.getByLabel(`新${noun}`, { exact: true }).fill(name)
  await page.getByRole('button', { name: `添加${noun}`, exact: true }).click()
  await expect(page.locator('.option-name').filter({ hasText: name })).toBeVisible()
}

test('选项设置管理顺序和颜色，商品选择保持精简并实时同步', async ({ page }) => {
  await login(page)
  await page.goto('/settings')
  await page.getByRole('button', { name: '选项管理', exact: true }).click()
  await expect(page).toHaveURL(/\/settings\/options$/)
  await add(page, '制作状态', '等待美术确认')
  await page.getByRole('button', { name: '蓝色', exact: true }).click()
  await add(page, '制作状态', '功能开发')
  await page.getByRole('button', { name: '橙色', exact: true }).click()
  await add(page, '制作状态', '联机验收')
  const art = page.locator('.option-row').filter({ hasText: '等待美术确认' })
  const first = page.locator('.option-row').first()
  const reordered = page.waitForResponse(response => response.url().endsWith('/api/product-options/statuses/order') && response.request().method() === 'PATCH')
  await art.getByRole('button', { name: '拖动制作状态“等待美术确认”排序', exact: true }).dragTo(first)
  expect((await reordered).ok()).toBeTruthy()
  await expect(page.locator('.option-row').first()).toContainText('等待美术确认')
  await page.getByRole('button', { name: '下移制作状态“等待美术确认”', exact: true }).click()
  await expect(page.locator('.option-row').nth(1)).toContainText('等待美术确认')
  const artHandle = page.getByRole('button', { name: '拖动制作状态“等待美术确认”排序', exact: true })
  await expect(artHandle).toBeFocused()
  await artHandle.press('ArrowUp')
  await expect(page.locator('.option-row').first()).toContainText('等待美术确认')
  await expect(page.locator('.option-list')).toHaveAttribute('aria-busy', 'false')
  await page.reload()
  await expect(page.locator('.option-row').first()).toContainText('等待美术确认')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: '/tmp/com-option-settings-desktop.png', fullPage: true })

  const productPage = await page.context().newPage()
  await productPage.goto('/products')
  await productPage.getByRole('button', { name: '创建商品', exact: true }).click()
  const form = productPage.getByRole('dialog', { name: '创建商品', exact: true })
  await form.getByLabel('商品中文名（可留空）').fill('选项管理验收商品')
  await expect(form.getByRole('button', { name: '制作状态', exact: true })).toContainText('构思中')
  await form.getByRole('button', { name: '制作状态', exact: true }).click()
  await expect(form.getByRole('option').first()).toHaveText('等待美术确认')
  await expect(form.getByRole('button', { name: /删除|新建/ })).toHaveCount(0)
  await expect(form.getByRole('link', { name: '管理制作状态 ↗', exact: true })).toHaveAttribute('target', '_blank')
  await form.getByRole('option', { name: '等待美术确认', exact: true }).click()
  await art.getByLabel('等待美术确认的颜色', { exact: true }).evaluate((input: HTMLInputElement) => { input.value = '#0891b2'; input.dispatchEvent(new Event('change', { bubbles: true })) })
  await expect(form.locator('.is-status .choice-selected .choice-color-dot')).toHaveCSS('background-color', 'rgb(8, 145, 178)')
  await expect(form.getByLabel('商品中文名（可留空）')).toHaveValue('选项管理验收商品')
  await form.getByRole('button', { name: '创建商品', exact: true }).click()
  const card = productPage.locator('.product-card').filter({ hasText: '选项管理验收商品' })
  await expect(card.locator('.status-dot')).toHaveCSS('background-color', 'rgb(8, 145, 178)')
  await productPage.getByRole('button', { name: '卡片', exact: true }).click()
  await expect(card.locator('.status-dot')).toHaveCSS('background-color', 'rgb(8, 145, 178)')
  await card.getByRole('link', { name: '选项管理验收商品', exact: true }).click()
  await productPage.getByRole('button', { name: '制作状态', exact: true }).click()
  await expect(productPage.locator('.record-option-select.is-status')).toHaveCSS('max-width', '352px')
  await expect.poll(async () => (await productPage.locator('.compact-select .choice-list').boundingBox())!.height).toBeLessThanOrEqual(220)
  await productPage.screenshot({ path: '/tmp/com-compact-status-selector.png' })

  await page.getByRole('tab', { name: '商品分类', exact: true }).click()
  for (const name of ['管理饮料', '管理零食', '管理其他']) await add(page, '商品分类', name)
  const category = page.locator('.option-row').filter({ hasText: '管理其他' })
  await category.getByRole('button', { name: '拖动商品分类“管理其他”排序', exact: true }).dragTo(page.locator('.option-row').first())
  await expect(page.locator('.option-row').first()).toContainText('管理其他')
  await expect(page.locator('.option-list')).toHaveAttribute('aria-busy', 'false')
  await page.reload()
  await expect(page.locator('.option-row').first()).toContainText('管理其他')
  await productPage.getByRole('combobox', { name: '搜索制作状态', exact: true }).press('Escape')
  await productPage.getByRole('button', { name: '商品分类', exact: true }).click()
  await expect(productPage.getByRole('option').nth(1)).toHaveText('管理其他')
  await expect(productPage.getByRole('option').first()).toHaveText('未设置商品分类')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: '/tmp/com-option-settings-mobile.png', fullPage: true })
  await page.getByRole('tab', { name: '商品分类', exact: true }).press('ArrowLeft')
  await expect(page.getByRole('tab', { name: '制作状态', exact: true })).toBeFocused()
  await expect(page.locator('.option-row').first()).toContainText('等待美术确认')
  await page.getByTitle('切换暗色').click()
  for (const width of [320, 390, 600, 900]) {
    await page.setViewportSize({ width, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '/tmp/com-option-settings-dark-mobile.png', fullPage: true })
})

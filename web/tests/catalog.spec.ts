test('配方面板分组、商品道具混用材料、数量合并和同产物多配方', async ({ page }) => {
  await login(page)
  const product = await seed(page,'products',{ chinese_name: '配方验收猕猴桃', category: '水果' })
  const material = await seed(page,'tools',{ chinese_name: '配方验收芯片' })
  const output = await seed(page,'tools',{ chinese_name: '配方验收智能玉镯' })
  await page.goto('/recipes')
  await page.getByRole('button', { name: '添加合成产物', exact: true }).click()
  let picker = page.getByRole('dialog', { name: '选择合成产物', exact: true })
  await expect(picker.locator('.picker-group-toggle').first()).toHaveAttribute('aria-expanded','true')
  await expect(picker.locator('.picker-group-toggle').last()).toHaveAttribute('aria-expanded','false')
  await picker.locator('.picker-group-toggle').last().click()
  await picker.locator('.choice-row').filter({ hasText: '配方验收智能玉镯' }).click()
  await expect(page).toHaveURL(/\/recipes\/[a-f0-9-]+$/)
  const groupURL = page.url()
  await page.getByRole('button', { name: '＋ 添加配方', exact: true }).click()
  let editor = page.locator('.recipe-editor').first()
  await editor.getByLabel('配方名称（可留空）', { exact: true }).fill('混合材料配方')
  for (const name of ['配方验收猕猴桃','配方验收芯片','配方验收猕猴桃']) {
    await editor.getByRole('button', { name: '＋ 添加材料', exact: true }).click()
    picker = page.getByRole('dialog', { name: '选择材料', exact: true })
    await picker.getByRole('searchbox', { name: '搜索商品和道具', exact: true }).fill(name)
    await picker.locator('.choice-row').filter({ hasText: name }).click()
  }
  await expect(editor.locator('.ingredient-row')).toHaveCount(2)
  await expect(editor.getByLabel('材料 1 数量', { exact: true })).toHaveValue('2')
  await editor.getByLabel('材料 2 数量', { exact: true }).fill('3')
  await editor.getByLabel('验证情况', { exact: true }).selectOption('verified')
  await editor.getByRole('button', { name: '保存这套配方', exact: true }).click()
  await expect(editor.getByRole('button', { name: '已保存', exact: true })).toBeVisible()
  await editor.getByRole('button', { name: '复制配方', exact: true }).click()
  await expect(page.locator('.recipe-editor')).toHaveCount(2)
  editor = page.locator('.recipe-editor').last()
  await editor.locator('.recipe-summary').click()
  await editor.getByLabel('配方名称（可留空）', { exact: true }).fill('替代配方')
  await editor.getByLabel('产出数量', { exact: true }).fill('2')
  await editor.getByRole('button', { name: '保存这套配方', exact: true }).click()
  await expect(editor.getByRole('button', { name: '已保存', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.recipe-editor')).toHaveCount(2)
  const group = await (await page.request.get(`/api/recipe-groups/${groupURL.split('/').at(-1)}`)).json()
  expect(group.output_id).toBe(output.id)
  expect(group.recipes[0].ingredients.map((i: { product_id: string }) => i.product_id)).toEqual([product.id,material.id])
  expect(group.recipes[1].output_quantity).toBe(2)
  await page.locator('.recipe-editor').first().locator('.recipe-summary').click()
  const first = page.locator('.recipe-editor').first()
  await first.getByLabel('条件／备注', { exact: true }).fill('尚未保存的本地配方修改')
  const me = await (await page.request.get('/api/auth/me')).json()
  const remote = await page.request.patch(`/api/recipes/${group.recipes[0].id}`, { headers: { 'X-CSRF-Token': me.csrf_token }, data: { ...group.recipes[0], id: undefined, group_id: undefined, created_by: undefined, created_at: undefined, updated_at: undefined, development_status_label: undefined, development_status_color: undefined, notes: '其他成员的配方修改', ingredients: group.recipes[0].ingredients.map((i: { product_id: string; category: string; quantity: number }) => ({ product_id: i.product_id, category: i.category, quantity: i.quantity })) } })
  expect(remote.ok(), await remote.text()).toBeTruthy()
  await expect(first.getByText('这套配方已有新修改，保存时会展示差异。', { exact: true })).toBeVisible()
  await expect(first.getByLabel('条件／备注', { exact: true })).toHaveValue('尚未保存的本地配方修改')
  await first.getByRole('button', { name: '保存这套配方', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '检测到同时编辑', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '将我的修改应用到最新版', exact: true }).click()
  await expect(first.getByRole('button', { name: '已保存', exact: true })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0,0))
  await page.screenshot({ path: '/tmp/com-catalog-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '/tmp/com-catalog-mobile.png', fullPage: true })
})

import { test, expect, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

const png = readFileSync('public/icon-192.png')
async function login(page: Page, username = 'admin') {
  await page.goto('/login')
  await page.getByLabel('用户名').fill(username)
  await page.getByLabel('密码', { exact: true }).fill(username === 'admin' ? 'e2e-admin-password' : 'e2e-member-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/ideas$/)
}
async function seed(page: Page, collection: string, data: Record<string, unknown>) {
  const me = await (await page.request.get('/api/auth/me')).json()
  const response = await page.request.post(`/api/${collection}`, { headers: { 'X-CSRF-Token': me.csrf_token }, data })
  expect(response.ok(), await response.text()).toBeTruthy()
  return response.json()
}


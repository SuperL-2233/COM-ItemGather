import { test, expect, type Page, type Locator } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/login')
  await page.getByLabel('用户名').fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('e2e-admin-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/ideas$/)
  return { 'X-CSRF-Token': (await (await page.request.get('/api/auth/me')).json()).csrf_token }
}
async function choose(dialog: Locator, label: string, value: string) {
  await dialog.getByRole('button', { name: label, exact: true }).click()
  await dialog.getByRole('option', { name: value, exact: true }).click()
}
async function noOverflow(page: Page) {
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
}

test('商品多选保持页面简洁，支持三项批量修改和明确清空', async ({ page }) => {
  const headers = await login(page)
  const companyResponse = await page.request.post('/api/companies', { headers, data: { chinese_name: '批量验收新公司' } })
  expect(companyResponse.ok()).toBeTruthy()
  const company = await companyResponse.json()
  expect((await page.request.post('/api/product-options/categories', { headers, data: { name: '批量验收新分类' } })).ok()).toBeTruthy()
  const statusResponse = await page.request.post('/api/product-options/statuses', { headers, data: { name: '批量验收待确认' } })
  expect(statusResponse.ok()).toBeTruthy()
  const state = (await statusResponse.json()).option
  const products = []
  for (const name of ['批量验收 商品甲', '批量验收 商品乙', '批量验收 商品丙']) {
    const response = await page.request.post('/api/products', { headers, data: { chinese_name: name, category: '原分类', description: '保留的商品说明' } })
    expect(response.ok()).toBeTruthy()
    products.push(await response.json())
  }
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/products')
  await page.getByRole('searchbox', { name: '搜索商品', exact: true }).fill('批量验收 商品')
  await expect(page.locator('.catalog-item')).toHaveCount(3)
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.screenshot({ path: '/tmp/com-products-batch-normal-desktop.png' })
  await page.getByRole('button', { name: '多选', exact: true }).click()
  const toolbar = page.getByRole('region', { name: '商品多选操作', exact: true })
  await expect(toolbar.getByRole('button', { name: '批量修改', exact: true })).toBeDisabled()
  const firstCheckbox = page.getByRole('checkbox', { name: `选择商品：${products[0].chinese_name}`, exact: true })
  await firstCheckbox.focus()
  await firstCheckbox.press('Space')
  await expect(firstCheckbox).toBeChecked()
  await page.locator('.catalog-item').filter({ hasText: products[1].chinese_name }).locator('h2').click()
  await expect(toolbar.getByRole('status')).toHaveText('已选 2 件商品')
  await expect(page).toHaveURL(/\/products$/)
  await page.screenshot({ path: '/tmp/com-products-batch-desktop.png' })
  await toolbar.getByRole('button', { name: '批量修改', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '批量修改商品', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: '应用到 2 件商品', exact: true })).toBeDisabled()
  for (const label of ['批量商品分类', '批量制作状态', '批量所属公司']) await expect(dialog.getByRole('button', { name: label, exact: true })).toHaveText('保持不变')
  await choose(dialog, '批量商品分类', '批量验收新分类')
  await choose(dialog, '批量制作状态', '批量验收待确认')
  await choose(dialog, '批量所属公司', company.chinese_name)
  await page.screenshot({ path: '/tmp/com-products-batch-dialog-desktop.png' })
  const saved = page.waitForResponse(response => response.url().endsWith('/api/products/batch') && response.request().method() === 'PATCH')
  await dialog.getByRole('button', { name: '应用到 2 件商品', exact: true }).click()
  const response = await saved
  expect(response.ok(), await response.text()).toBeTruthy()
  expect(response.request().postDataJSON()).toEqual({ items: expect.arrayContaining(products.slice(0, 2).map(item => ({ id: item.id, version: item.version }))), category: '批量验收新分类', development_status: state.value, company_id: company.id })
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  for (const [index, original] of products.entries()) {
    const item = await (await page.request.get(`/api/products/${original.id}`)).json()
    expect(item.category).toBe(index < 2 ? '批量验收新分类' : '原分类')
    expect(item.company_id).toBe(index < 2 ? company.id : '')
    expect(item.development_status).toBe(index < 2 ? state.value : 'concept')
    expect(item.description).toBe('保留的商品说明')
  }

  await page.getByRole('button', { name: '卡片', exact: true }).click()
  await page.getByRole('button', { name: '多选', exact: true }).click()
  await page.getByRole('checkbox', { name: `选择商品：${products[0].chinese_name}`, exact: true }).check()
  for (const width of [320, 390, 600]) {
    await page.setViewportSize({ width, height: 844 })
    await noOverflow(page)
    await expect(toolbar.getByRole('button', { name: '批量修改', exact: true })).toBeVisible()
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '/tmp/com-products-batch-grid-mobile.png', fullPage: true })
  await toolbar.getByRole('button', { name: '批量修改', exact: true }).click()
  await choose(dialog, '批量商品分类', '清空分类')
  await choose(dialog, '批量所属公司', '清空公司')
  await page.screenshot({ path: '/tmp/com-products-batch-dialog-mobile.png' })
  const cleared = page.waitForResponse(response => response.url().endsWith('/api/products/batch') && response.request().method() === 'PATCH')
  await dialog.getByRole('button', { name: '应用到 1 件商品', exact: true }).click()
  const clearResponse = await cleared
  expect(clearResponse.ok()).toBeTruthy()
  expect(clearResponse.request().postDataJSON()).toEqual({ items: [{ id: products[0].id, version: 2 }], category: '', company_id: '' })
  await expect(dialog).toHaveCount(0)
  const clearedProduct = await (await page.request.get(`/api/products/${products[0].id}`)).json()
  expect(clearedProduct.category).toBe('')
  expect(clearedProduct.company_id).toBe('')
  expect(clearedProduct.development_status).toBe(state.value)
  await page.getByRole('button', { name: '列表', exact: true }).click()
  await page.getByTitle('切换暗色').click()
  await page.getByRole('button', { name: '多选', exact: true }).click()
  await toolbar.getByRole('button', { name: '全选已显示', exact: true }).click()
  await noOverflow(page)
  await page.screenshot({ path: '/tmp/com-products-batch-list-dark-mobile.png', fullPage: true })
  await toolbar.getByRole('button', { name: '批量修改', exact: true }).click()
  await choose(dialog, '批量制作状态', '已完成')
  await noOverflow(page)
  await page.screenshot({ path: '/tmp/com-products-batch-dialog-dark-mobile.png' })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(toolbar.getByRole('button', { name: '批量修改', exact: true })).toBeFocused()
  await toolbar.getByRole('button', { name: '取消多选', exact: true }).click()
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '多选', exact: true })).toBeFocused()
})

test('多选跨加载保留勾选，搜索清空选择，并发冲突整批不保存', async ({ page }) => {
  const headers = await login(page)
  const products = []
  for (let index = 0; index < 35; index++) {
    const response = await page.request.post('/api/products', { headers, data: { chinese_name: `批量分页 ${String(index).padStart(2, '0')}`, category: '分页原分类' } })
    expect(response.ok()).toBeTruthy()
    products.push(await response.json())
  }
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.goto('/products')
  const search = page.getByRole('searchbox', { name: '搜索商品', exact: true })
  await search.fill('批量分页')
  await expect(page.locator('.catalog-item')).toHaveCount(30)
  await page.getByRole('button', { name: '多选', exact: true }).click()
  const toolbar = page.getByRole('region', { name: '商品多选操作', exact: true })
  await toolbar.getByRole('button', { name: '全选已显示', exact: true }).click()
  await expect(toolbar.getByRole('status')).toHaveText('已选 30 件商品')
  await page.locator('.load-more-status').scrollIntoViewIfNeeded()
  await expect(page.locator('.catalog-item')).toHaveCount(35)
  await expect(page.getByRole('checkbox', { checked: true })).toHaveCount(30)
  await toolbar.getByRole('button', { name: '全选已显示', exact: true }).click()
  await expect(toolbar.getByRole('status')).toHaveText('已选 35 件商品')
  await toolbar.getByRole('button', { name: '取消全选', exact: true }).click()
  await expect(toolbar.getByRole('status')).toHaveText('已选 0 件商品')
  await page.getByRole('checkbox').first().check()
  await search.fill('批量分页 00')
  expect(await page.getByRole('checkbox').first().isDisabled()).toBe(true)
  await expect(page.locator('.catalog-item')).toHaveCount(1)
  await expect(toolbar.getByRole('status')).toHaveText('已选 0 件商品')
  await search.fill('批量分页')
  await expect(page.locator('.catalog-item')).toHaveCount(30)
  const selected = products.slice(-2)
  for (const item of selected) await page.getByRole('checkbox', { name: `选择商品：${item.chinese_name}`, exact: true }).check()
  await toolbar.getByRole('button', { name: '批量修改', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '批量修改商品', exact: true })
  await choose(dialog, '批量制作状态', '已完成')
  await dialog.getByRole('button', { name: '批量商品分类', exact: true }).click()
  const categorySearch = dialog.getByRole('combobox', { name: '搜索批量商品分类', exact: true })
  await categorySearch.fill('分页')
  const optionsRefreshed = page.waitForResponse(response => new URL(response.url()).pathname === '/api/product-options/categories')
  const changed = await page.request.patch(`/api/products/${selected[1].id}`, { headers, data: { version: selected[1].version, description: '另一位成员的修改' } })
  expect(changed.ok()).toBeTruthy()
  await optionsRefreshed
  await expect(categorySearch).toBeFocused()
  await expect(categorySearch).toHaveValue('分页')
  await categorySearch.press('Escape')
  await expect(page.locator('.product-catalog')).toHaveAttribute('aria-busy', 'false')
  const conflicted = page.waitForResponse(response => response.url().endsWith('/api/products/batch') && response.request().method() === 'PATCH')
  await dialog.getByRole('button', { name: '应用到 2 件商品', exact: true }).click()
  expect((await conflicted).status()).toBe(409)
  await expect(dialog.getByRole('alert')).toContainText('本次未保存')
  for (const original of selected) {
    const item = await (await page.request.get(`/api/products/${original.id}`)).json()
    expect(item.development_status).toBe('concept')
    expect(item.category).toBe('分页原分类')
  }
  await dialog.getByRole('button', { name: '重新选择商品', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(toolbar.getByRole('status')).toHaveText('已选 0 件商品')
  await expect(page.getByRole('button', { name: '创建商品', exact: true })).toBeVisible()
})

import { test, expect, type Page, type Locator } from '@playwright/test'

async function login(page: Page, member = false) {
  await page.goto('/login')
  await page.getByLabel('用户名').fill(member ? 'member' : 'admin')
  await page.getByLabel('密码', { exact: true }).fill(member ? 'e2e-member-password' : 'e2e-admin-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/ideas$/)
}
async function request(page: Page, method: 'post' | 'patch', path: string, data: object) {
  const me = await (await page.request.get('/api/auth/me')).json()
  const result = await page.request[method](`/api/${path}`,{ headers: { 'X-CSRF-Token': me.csrf_token }, data })
  expect(result.ok(),await result.text()).toBeTruthy()
  return result.json()
}
async function createOption(page: Page, scope: Locator, label: string, name: string) {
  const kind = label === '制作状态' ? 'statuses' : 'categories'
  const manager = await page.context().newPage()
  try {
    await manager.goto(`/settings/options?kind=${kind}`)
    await manager.getByLabel(`新${label}`, { exact: true }).fill(name)
    await manager.getByRole('button', { name: `添加${label}`, exact: true }).click()
    await expect(manager.locator('.option-name').filter({ hasText: name })).toBeVisible()
  } finally { await manager.close() }
  await scope.getByRole('button', { name: label, exact: true }).click()
  await scope.getByRole('combobox', { name: `搜索${label}`, exact: true }).fill(name)
  await expect(scope.getByRole('button', { name: /删除/ })).toHaveCount(0)
  await scope.getByRole('option', { name, exact: true }).click()
}


  await expect(page.getByRole('button',{ name: '商品分类', exact: true })).toContainText('键盘新分类')
  await expect(page.getByRole('button',{ name: '制作状态', exact: true })).toContainText('待联机校验')
  await expect(page.getByRole('button',{ name: '所属公司', exact: true })).toContainText('原位快速创建公司')

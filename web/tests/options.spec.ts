test('已有选项搜索、取消和中文输入确认不会误写表单或选项', async ({ page }) => {
  await login(page)
  const item = await request(page,'post','products',{ chinese_name: '取消选项验收商品', category: '保留原分类' })
  await request(page,'post','products',{ chinese_name: '下拉搜索对照商品', category: '可搜索已有分类' })
  await page.goto(`/products/${item.id}`)
  await page.getByRole('button',{ name: '商品分类', exact: true }).click()
  let search = page.getByRole('combobox',{ name: '搜索商品分类', exact: true })
  await search.fill('已有分类')
  await expect(page.getByRole('option',{ name: '可搜索已有分类', exact: true })).toBeVisible()
  await expect(page.getByRole('option',{ name: '保留原分类', exact: true })).toHaveCount(0)
  await search.dispatchEvent('keydown',{ key: 'Enter', code: 'Enter', isComposing: true, bubbles: true })
  await expect(page.getByRole('textbox',{ name: '新分类名称', exact: true })).toHaveCount(0)
  await search.press('Escape')
  await expect(page.getByRole('button',{ name: '商品分类', exact: true })).toContainText('保留原分类')
  await page.getByRole('button',{ name: '商品分类', exact: true }).click()
  search = page.getByRole('combobox',{ name: '搜索商品分类', exact: true })
  await search.fill('不应保存的搜索文字')
  await search.press('Enter')
  await expect(page.getByRole('textbox', { name: '新分类名称', exact: true })).toHaveCount(0)
  await expect(search).toBeFocused()
  await search.press('Escape')
  await expect(page.getByRole('button', { name: '商品分类', exact: true })).toContainText('保留原分类')
  await page.getByRole('button', { name: '商品分类', exact: true }).click()
  await search.fill('临时搜索并切换焦点')
  await search.press('Tab')
  const manage = page.getByRole('link', { name: '管理商品分类 ↗', exact: true })
  await expect(manage).toBeFocused()
  await manage.press('Tab')
  await expect(search).toHaveCount(0)
  await expect(page.getByRole('button',{ name: '已保存', exact: true })).toBeVisible()
  const choices = await (await page.request.get('/api/product-options/categories')).json()
  expect(choices.items.some((option: {label:string}) => option.label.startsWith('不应保存'))).toBeFalsy()
  await page.getByRole('button',{ name: '商品分类', exact: true }).click()
  await search.fill('已有分类')
  await search.press('ArrowUp')
  await search.press('Enter')
  await expect(page.getByRole('button',{ name: '商品分类', exact: true })).toContainText('可搜索已有分类')
  await page.getByRole('button',{ name: '保存修改', exact: true }).click()
  await expect(page.getByRole('button',{ name: '已保存', exact: true })).toBeVisible()
  await page.getByRole('button',{ name: '商品分类', exact: true }).click()
  await page.getByRole('option',{ name: '未设置商品分类', exact: true }).click()
  await expect(page.getByRole('button',{ name: '商品分类', exact: true })).toContainText('未设置商品分类')
  await page.getByRole('button',{ name: '保存修改', exact: true }).click()
  await expect(page.getByRole('button',{ name: '已保存', exact: true })).toBeVisible()
  expect((await (await page.request.get(`/api/products/${item.id}`)).json()).category).toBe('')
})

test('设置创建可失败重试，选项实时共享，手机下拉保持在视口内', async ({ page,browser }) => {
  await login(page)
  const item = await request(page,'post','products',{ chinese_name: '共享选项验收商品' })
  await page.goto(`/products/${item.id}`)
  const context = await browser.newContext()
  const manager = await page.context().newPage()
  try {
    const second = await context.newPage()
    await login(second,true)
    await second.goto(`/products/${item.id}`)
    await second.getByRole('button',{ name: '商品分类', exact: true }).click()
    await second.getByRole('combobox',{ name: '搜索商品分类', exact: true }).fill('重试后共享分类')
    await manager.goto('/settings/options?kind=categories')
    await manager.route('**/api/product-options/categories',async route => {
      if (route.request().method() === 'POST') await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'temporary', message: '测试暂时无法保存' } }) })
      else await route.continue()
    })
    await manager.getByLabel('新商品分类', { exact: true }).fill('重试后共享分类')
    await manager.getByRole('button', { name: '添加商品分类', exact: true }).click()
    await expect(manager.getByRole('alert')).toContainText('测试暂时无法保存')
    await expect(manager.getByLabel('新商品分类', { exact: true })).toHaveValue('重试后共享分类')
    await manager.unroute('**/api/product-options/categories')
    await manager.getByRole('button', { name: '添加商品分类', exact: true }).click()
    await expect(manager.locator('.option-name').filter({ hasText: '重试后共享分类' })).toBeVisible()
    await expect(second.getByRole('option',{ name: '重试后共享分类', exact: true })).toBeVisible()
    await second.getByRole('option',{ name: '重试后共享分类', exact: true }).click()
    const newState = await request(page,'post','product-options/statuses',{ name: '等待复核状态' })
    await second.getByRole('button',{ name: '制作状态', exact: true }).click()
    await second.getByRole('combobox',{ name: '搜索制作状态', exact: true }).fill('等待复核状态')
    await second.getByRole('option',{ name: '等待复核状态', exact: true }).click()
    const current = await (await page.request.get(`/api/products/${item.id}`)).json()
    await request(page,'patch',`products/${item.id}`,{ version: current.version, development_status: 'completed' })
    await second.getByRole('button',{ name: '保存修改', exact: true }).click()
    const conflict = second.getByRole('dialog',{ name: '检测到同时编辑', exact: true })
    await expect(conflict).toContainText('等待复核状态')
    await expect(conflict).toContainText('已完成')
    await expect(conflict).not.toContainText(newState.option.value)
    await second.getByRole('button',{ name: '使用服务器版本', exact: true }).click()
    await page.setViewportSize({ width: 390,height: 844 })
    await page.getByRole('button',{ name: '制作状态', exact: true }).click()
    await page.getByRole('combobox',{ name: '搜索制作状态', exact: true }).fill('构思')
    const latest = await (await page.request.get(`/api/products/${item.id}`)).json()
    await request(page,'patch',`products/${item.id}`,{ version: latest.version, development_status: 'design' })
    await expect(page.getByRole('combobox',{ name: '搜索制作状态', exact: true })).toHaveAttribute('placeholder','设计中')
    await expect(page.getByRole('combobox',{ name: '搜索制作状态', exact: true })).toHaveValue('构思')
    const panel = page.locator('.search-select-panel')
    await expect(panel).toBeVisible()
    const box = await panel.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x+box!.width).toBeLessThanOrEqual(390)
    expect(box!.y).toBeGreaterThanOrEqual(0)
    expect(box!.y+box!.height).toBeLessThanOrEqual(844)
    await page.screenshot({ path: '/tmp/com-options-mobile.png' })
  } finally { await context.close(); await manager.close() }
})
